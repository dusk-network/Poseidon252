use dusk_bls12_381::BlsScalar;
use dusk_poseidon::{Domain, Hash};

// Generated through the public Hash API in release mode from
// dusk-poseidon v0.42.0-rc.0 at 2b6b544. A mismatch is a compatibility break,
// not a reason to regenerate these expected values.
#[test]
fn public_hash_known_answer_vectors() {
    let input = [
        BlsScalar::from(1u64),
        BlsScalar::from(2u64),
        BlsScalar::from(3u64),
        BlsScalar::from(4u64),
        BlsScalar::from(5u64),
        BlsScalar::from(6u64),
    ];

    for (domain, input, expected) in [
        (
            Domain::Merkle2,
            &input[..2],
            [
                0x67, 0xb7, 0x15, 0x27, 0x42, 0x76, 0x02, 0xb6, 0x80, 0x5f,
                0x74, 0x31, 0x26, 0xef, 0x61, 0x0b, 0x52, 0xcc, 0x58, 0xa6,
                0x4b, 0x70, 0xd8, 0x93, 0x60, 0x5a, 0x7e, 0x66, 0xac, 0x24,
                0x9c, 0x1e,
            ],
        ),
        (
            Domain::Merkle4,
            &input[..4],
            [
                0x07, 0xba, 0x3d, 0xa0, 0xb3, 0x2e, 0x6e, 0x53, 0x7e, 0x2c,
                0x24, 0xf3, 0x78, 0xb5, 0x66, 0x89, 0xe0, 0x41, 0xcb, 0x91,
                0x62, 0xe0, 0xd6, 0x5b, 0xc8, 0xf4, 0xd4, 0xb2, 0xbe, 0x39,
                0x8d, 0x6c,
            ],
        ),
        (
            Domain::Encryption,
            &input[..3],
            [
                0x5d, 0x87, 0x9a, 0x0f, 0x83, 0xc1, 0xe6, 0x6b, 0x47, 0x2a,
                0x4b, 0x9b, 0xf3, 0x48, 0xfc, 0x0c, 0xf4, 0x1e, 0x92, 0x33,
                0x8e, 0x70, 0xe0, 0x86, 0xe2, 0x63, 0x4f, 0x0f, 0x7d, 0x0c,
                0x11, 0x65,
            ],
        ),
        (
            Domain::Other,
            &input[..3],
            [
                0xf5, 0x55, 0x87, 0x58, 0xaa, 0x44, 0xaa, 0xbe, 0xd7, 0x59,
                0xc7, 0x09, 0xc8, 0xcb, 0x75, 0xe9, 0xe7, 0xc2, 0x7a, 0xd0,
                0x33, 0x9e, 0x61, 0x6a, 0x65, 0x78, 0xa4, 0xac, 0x99, 0x77,
                0x97, 0x6b,
            ],
        ),
        (
            Domain::Other,
            &input,
            [
                0xe5, 0x6e, 0x7e, 0xb4, 0x52, 0xb5, 0x2f, 0xda, 0x93, 0x81,
                0x3f, 0xe0, 0x63, 0x0d, 0xf8, 0x8b, 0x13, 0x2f, 0x9d, 0x58,
                0x3a, 0xe4, 0x4d, 0xe2, 0xbf, 0x91, 0x0f, 0x27, 0xb8, 0xb9,
                0x46, 0x4e,
            ],
        ),
    ] {
        assert_eq!(
            Hash::digest(domain, input)[0].to_bytes(),
            expected,
            "{domain:?}, {} inputs",
            input.len()
        );
    }

    assert_eq!(
        Hash::digest_truncated(Domain::Other, &input[..3])[0].to_bytes(),
        [
            0xf5, 0x55, 0x87, 0x58, 0xaa, 0x44, 0xaa, 0xbe, 0xd7, 0x59, 0xc7,
            0x09, 0xc8, 0xcb, 0x75, 0xe9, 0xe7, 0xc2, 0x7a, 0xd0, 0x33, 0x9e,
            0x61, 0x6a, 0x65, 0x78, 0xa4, 0xac, 0x99, 0x77, 0x97, 0x03,
        ]
    );

    let mut hash = Hash::new(Domain::Other);
    hash.update(&input[..4]);
    hash.output_len(5);
    let output = hash.finalize();
    assert_eq!(
        [
            output[0].to_bytes(),
            output[1].to_bytes(),
            output[2].to_bytes(),
            output[3].to_bytes(),
            output[4].to_bytes(),
        ],
        [
            [
                0x43, 0x7a, 0x97, 0xd7, 0x9e, 0xa4, 0x8b, 0x5e, 0xbe, 0x4f,
                0x61, 0x49, 0x35, 0x83, 0x7b, 0x19, 0x0e, 0x89, 0x5b, 0x95,
                0xe1, 0x38, 0x75, 0x3e, 0xa5, 0x32, 0xef, 0xad, 0x20, 0xf3,
                0x6d, 0x4f,
            ],
            [
                0x1c, 0xf4, 0xd7, 0x7f, 0xad, 0xd4, 0xde, 0x54, 0x95, 0xf5,
                0x55, 0xb6, 0x25, 0x0b, 0xfb, 0x83, 0xa0, 0x82, 0xda, 0x42,
                0x25, 0xd2, 0x69, 0x57, 0xeb, 0xe1, 0x68, 0x0f, 0xae, 0xbe,
                0xac, 0x5b,
            ],
            [
                0xfe, 0x07, 0x74, 0x4e, 0x8c, 0xde, 0xe3, 0x82, 0xa2, 0x4d,
                0xbf, 0x13, 0xa9, 0x20, 0xec, 0xce, 0xa3, 0xe2, 0x1f, 0x06,
                0x71, 0x7d, 0xf1, 0xaf, 0x6b, 0xc2, 0x01, 0xdf, 0x04, 0x21,
                0x68, 0x32,
            ],
            [
                0x56, 0x8f, 0x89, 0xc0, 0x4c, 0x46, 0xd0, 0x22, 0xb1, 0x89,
                0xa1, 0x75, 0xc8, 0x17, 0x9d, 0xe7, 0x97, 0x44, 0xfc, 0xfe,
                0x7f, 0x0c, 0x02, 0x67, 0xf2, 0x55, 0x0c, 0x34, 0x1e, 0x56,
                0x0a, 0x3e,
            ],
            [
                0x58, 0xe8, 0x06, 0xb5, 0xe7, 0x11, 0x10, 0x3a, 0x5e, 0x7f,
                0x33, 0x72, 0x92, 0x97, 0xdd, 0xa0, 0x61, 0x95, 0x24, 0xa3,
                0xe9, 0x02, 0x6a, 0xa7, 0xc5, 0x98, 0xbb, 0x3a, 0x05, 0x99,
                0x17, 0x51,
            ],
        ]
    );
}
